import assert from 'node:assert/strict';
import { dashboardQuality, comparableAverageUnit } from '../src/engine/dashboard-quality.js';
const sale=(props={})=>({acc:'511',inv:'INV1',cust:'Customer A',prod:'P1',uom:'PCS',vnd:100,tot:60,fq:2,fin:'FIFO COGS',status:'PASS',...props});
const result=(sales,totals={cogsA:60,consA:0,consQ:0})=>({sales,totals});
const good=dashboardQuality(result([sale()]));
assert.equal(good.status,'PASS');
assert.equal(good.issues.length,0);
const stale=dashboardQuality(result([sale()]),'OUTDATED');
assert.equal(stale.status,'BLOCK');
assert.ok(stale.issues.some(i=>i.id==='step5-stale'));
const missing=dashboardQuality(result([sale({tot:0})],{cogsA:0,consA:0,consQ:0}));
assert.ok(missing.issues.some(i=>i.id==='zero-cogs'));
const alias=dashboardQuality(result([sale({cust:'Techtronic Ltd.',vnd:60,tot:30}),sale({cust:'TECHTRONIC LTD.',vnd:40,tot:30})]));
assert.equal(alias.status,'REVIEW');
assert.ok(alias.issues.some(i=>i.id==='customer-alias'));
assert.equal(comparableAverageUnit(result([sale()])).value,50);
assert.equal(comparableAverageUnit(result([sale(),sale({prod:'P2'})])).value,null);
assert.equal(comparableAverageUnit(result([sale(),sale({uom:'KG'})])).value,null);
assert.equal(comparableAverageUnit(null).value,null);
console.log('PASS executive dashboard data quality and comparable unit checks');
